const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_EXECUTABLE_PATH?{executablePath:process.env.CHROMIUM_EXECUTABLE_PATH,args:['--no-sandbox','--disable-dev-shm-usage']}:{})});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:8000');
  await page.click('#try-demo');
  await page.click('#overlay-toggle');
  await page.waitForSelector('#overlay-panel .js-plotly-plot');
  assert(await page.locator('#panels').isHidden());
  assert(await page.locator('#fit-all').isHidden());
  assert(await page.locator('#smooth-control').isHidden());
  let traces=await page.locator('#overlay-panel .chart').evaluate(e=>e.data);
  assert.equal(traces.length,3);
  assert(traces.every(t=>t.type==='scatter'));
  assert.equal(new Set(traces.map(t=>t.marker.color)).size,3);
  assert.equal(new Set(traces.map(t=>t.marker.symbol)).size,3);
  assert.deepEqual(traces.map(t=>t.x.length).sort((a,b)=>a-b),[48,60,72]);
  const own=traces.find(t=>t.name.startsWith('自社'));
  assert.equal(own.marker.color,'#67e8f9');
  assert.equal(own.marker.symbol,'circle');
  assert(traces.every(t=>t.customdata.every(c=>c[0].includes('サンプル店'))));
  await page.locator('#overlay-panel .legendtoggle').first().click();
  await page.waitForFunction(()=>document.querySelector('#overlay-panel .chart').data.find(t=>t.name.startsWith('自社')).visible==='legendonly');
  await page.click('label[for="ax-km"]');
  await page.waitForFunction(()=>document.querySelector('#overlay-panel .chart')._fullLayout.xaxis.title.text==='走行距離');
  traces=await page.locator('#overlay-panel .chart').evaluate(e=>e.data);
  assert.equal(traces.find(t=>t.name.startsWith('自社')).visible,'legendonly','legend selection lost');
  await page.locator('#overlay-panel .legendtoggle').first().click();
  await page.waitForFunction(()=>document.querySelector('#overlay-panel .chart').data.find(t=>t.name.startsWith('自社')).visible!== 'legendonly');
  await page.screenshot({path:'/workspace/artifacts/overlay-comparison.png',fullPage:true});
  await page.click('label[for="ax-year"]');
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(300);
  const labels=await page.locator('#overlay-panel .xtick text').evaluateAll(es=>es.map(e=>{const r=e.getBoundingClientRect();return {left:r.left,right:r.right};}));
  for(let i=1;i<labels.length;i++)assert(labels[i].left-labels[i-1].right>=4,'overlay year labels overlap after resize');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.click('#overlay-toggle');
  assert(await page.locator('#overlay-panel').isHidden());
  assert(await page.locator('#panels').isVisible());
  assert.deepEqual(await page.locator('#panels .chart').first().evaluate(e=>e.data.map(t=>t.type)),['heatmap']);
  // Fresh scrape while overlay mode is active must still auto-close the sidebar.
  await page.click('#overlay-toggle');
  await page.fill('#own-url','https://example.com/own');
  await page.locator('#rivals .url').first().fill('https://example.com/rival');
  await page.route('**/api/analyze?**',route=>route.fulfill({json:{vehicles:[{price:100,year:2024,mileage:20,text:'テスト'}],pages:1,warnings:[]}}));
  await page.click('#go');
  await page.waitForSelector('#app.collapsed');
  assert.equal(await page.locator('#overlay-panel .chart').evaluate(e=>e.data.length),2);
  await page.click('#rail');
  await page.unroute('**/api/analyze?**');
  await page.route('**/api/analyze?**',route=>route.fulfill({status:400,json:{detail:'URL error'}}));
  await page.click('#go');
  await page.waitForFunction(()=>!document.querySelector('#go').disabled);
  assert(await page.locator('#overlay-panel .failed').isVisible());
  assert(await page.locator('#setup-body').isVisible());
  assert.deepEqual(errors,[]);
  console.log('PASS: three-company overlay, unique colors/shapes, own cyan, company hover data, legend toggles preserved, both axes, mobile and restore');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
